def render_markdown(report: Mapping[str, Any]) -> str:
    """Render the report as Markdown for sharing and archiving."""

    analysis = report.get("analysis") or {}
    lines: list[str] = []
    add = lines.append

    add(f"# Site selection report: {analysis.get('name')}")
    add("")
    add(f"*Generated: {report.get('generated_at')}*")
    add("")
    add("## Executive summary")
    add("")
    summary = report.get("executive_summary") or {}
    add(str(summary.get("headline") or ""))
    add("")
    for paragraph in summary.get("paragraphs") or []:
        add(paragraph)
        add("")

    recommendation = summary.get("recommendation")
    if recommendation:
        add("**Recommended next steps**")
        add("")
        for step in recommendation.get("next_steps") or []:
            add(f"- {step}")
        add("")

    add("## Scope")
    add("")
    add(f"- **Business type:** {analysis.get('business_type') or 'Not specified'}")
    add(f"- **Acquisition mode:** {analysis.get('acquisition_mode')}")
    add(f"- **Aggregation method:** {analysis.get('aggregation_method')}")
    add("")

    add("## Shortlist")
    add("")
    add("| # | Site | Score | Initial investment | Monthly cost |")
    add("| --- | --- | --- | --- | --- |")
    for site in report.get("top_sites") or []:
        cost = site.get("cost") or {}
        totals = cost.get("totals") or {}
        add(
            f"| {site.get('position')} | {site.get('site_name')} | "
            f"{float(site.get('score')):.4f} | "
            f"{_format_money(totals.get('initial_investment_total'))} | "
            f"{_format_money(totals.get('recurring_monthly_total'))} |"
        )
    add("")

    for site in report.get("top_sites") or []:
        add(f"### {site.get('position')}. {site.get('site_name')}")
        add("")
        if site.get("why"):
            add(str(site["why"]))
            add("")
        if site.get("caveats"):
            add("**Caveats**")
            add("")
            for caveat in site["caveats"]:
                add(f"- {caveat}")
            add("")

    add("## Cost analysis")
    add("")
    add("| Site | Acquisition | Setup | Monthly | Annual | Complete |")
    add("| --- | --- | --- | --- | --- | --- |")
    for item in report.get("cost_analysis") or []:
        add(
            f"| {item.get('site_id')} | "
            f"{_format_money(item.get('acquisition_total'))} | "
            f"{_format_money(item.get('setup_total'))} | "
            f"{_format_money(item.get('recurring_monthly_total'))} | "
            f"{_format_money(item.get('recurring_annual_total'))} | "
            f"{'yes' if item.get('is_complete') else 'no'} |"
        )
    add("")

    add("## Data quality and limitations")
    add("")
    for limitation in (report.get("data_quality") or {}).get("limitations") or []:
        add(f"- **{limitation.get('title')}** â€” {limitation.get('detail')}")
    add("")

    add("## Assumptions")
    add("")
    for assumption in report.get("assumptions") or []:
        add(f"- {assumption}")
    add("")

    add("---")
    add("")
    add(str(report.get("statement") or ""))

    return "\n".join(lines)


def render_html(report: Mapping[str, Any]) -> str:
    """Render the report as a self-contained printable HTML document."""

    from html import escape

    analysis = report.get("analysis") or {}
    summary = report.get("executive_summary") or {}

    def esc(value: Any) -> str:
        return escape(str(value if value is not None else ""))

    site_rows = []
    for site in report.get("top_sites") or []:
        cost = site.get("cost") or {}
        totals = cost.get("totals") or {}
        site_rows.append(
            "<tr>"
            f"<td>{esc(site.get('position'))}</td>"
            f"<td>{esc(site.get('site_name'))}</td>"
            f"<td class='num'>{esc(site.get('score'))}</td>"
            f"<td class='num'>{esc(_format_money(totals.get('initial_investment_total')))}</td>"
            f"<td class='num'>{esc(_format_money(totals.get('recurring_monthly_total')))}</td>"
            "</tr>"
        )

    detail_blocks = []
    for site in report.get("top_sites") or []:
        caveats = "".join(f"<li>{esc(item)}</li>" for item in site.get("caveats") or [])
        detail_blocks.append(
            f"<section class='card'>"
            f"<h3>{esc(site.get('position'))}. {esc(site.get('site_name'))}</h3>"
            f"<p>{esc(site.get('why') or '')}</p>"
            + (f"<h4>Caveats</h4><ul>{caveats}</ul>" if caveats else "")
            + "</section>"
        )

    limitation_items = "".join(
        f"<li><strong>{esc(item.get('title'))}</strong> &mdash; {esc(item.get('detail'))}</li>"
        for item in (report.get("data_quality") or {}).get("limitations") or []
    )
