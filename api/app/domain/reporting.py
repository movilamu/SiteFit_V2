"""Executive decision report generation.

The report is assembled from the deterministic results the platform has
already computed: the ranking, the score decomposition, the requirement
evaluation, the cost assessment, the sensitivity analysis and the data
quality report.  Nothing is generated by a language model, and every
figure carries the provenance it was computed with.

The report states its own limits prominently.  It is a decision-support
document, not a forecast, and it says so in the summary, the methodology
section and the closing statement.
"""

from __future__ import annotations

from datetime import datetime, timezone
from typing import Any, Mapping, Optional, Sequence

REPORT_VERSION = "2.0"


def _now_iso() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def _format_money(value: Optional[float]) -> str:
    if value is None:
        return "unavailable"
    if abs(value) >= 10_000_000:
        return f"{value / 10_000_000:,.2f} crore"
    if abs(value) >= 100_000:
        return f"{value / 100_000:,.2f} lakh"
    return f"{value:,.0f}"


def build_report(
    analysis: Mapping[str, Any],
    ranking: Sequence[Mapping[str, Any]],
    explanations: Sequence[Mapping[str, Any]],
    cost_assessments: Sequence[Mapping[str, Any]],
    property_results: Sequence[Mapping[str, Any]],
    sensitivity: Mapping[str, Any],
    data_quality: Mapping[str, Any],
    comparison: Optional[Mapping[str, Any]] = None,
) -> dict[str, Any]:
    """Assemble the full executive report payload."""

    top_sites = list(ranking)[:3]
    top_site_ids = {str(item.get("site_id")) for item in top_sites}

    selected_explanations = [
        explanation
        for explanation in explanations
        if str(explanation.get("site_id")) in top_site_ids
    ]

    costs_by_site = {
        str(item.get("site_id")): item for item in cost_assessments
    }
    properties_by_site: dict[str, list[Mapping[str, Any]]] = {}
    for entry in property_results:
        site_id = str(entry.get("site_id"))
        properties_by_site.setdefault(site_id, [])
        for opportunity in entry.get("opportunities") or []:
            properties_by_site[site_id].append(opportunity)

    def _site_entry(
        position: int, site: Mapping[str, Any]
    ) -> dict[str, Any]:
        site_id = str(site.get("site_id"))
        explanation = next(
            (
                item
                for item in selected_explanations
                if str(item.get("site_id")) == site_id
            ),
            None,
        )
        cost = costs_by_site.get(site_id)
        return {
            "position": position,
            "site_id": site_id,
            "site_name": site.get("name") or f"Site {site_id}",
            "score": site.get("score"),
            "rank": site.get("rank"),
            "latitude": site.get("latitude"),
            "longitude": site.get("longitude"),
            "why": explanation.get("summary") if explanation else None,
            "strengths": (explanation or {}).get("strengths") or [],
            "weaknesses": (explanation or {}).get("weaknesses") or [],
            "caveats": (explanation or {}).get("caveats") or [],
            "cost": cost,
            "property_opportunities": properties_by_site.get(site_id, []),
        }

    sites_section: list[dict[str, Any]] = [
        _site_entry(position, site)
        for position, site in enumerate(top_sites, start=1)
    ]

    # The narrative focuses on the leaders, but the report keeps the
    # whole ranking so that an export carries the ranking that was
    # produced rather than only its first three rows.
    shortlist: list[dict[str, Any]] = [
        _site_entry(position, site)
        for position, site in enumerate(ranking, start=1)
    ]

    report: dict[str, Any] = {
        "report_version": REPORT_VERSION,
        "generated_at": _now_iso(),
        "analysis": {
            "name": analysis.get("name") or "Untitled analysis",
            "business_type": analysis.get("business_type"),
            "acquisition_mode": analysis.get("acquisition_mode") or "either",
            "location": analysis.get("location") or {},
            "requirements": analysis.get("requirements") or {},
            "weights": analysis.get("weights") or {},
            "aggregation_method": analysis.get("aggregation_method") or "weighted_sum",
            "criteria_coverage": analysis.get("criteria_coverage") or {},
        },
        "executive_summary": _executive_summary(
            analysis, top_sites, selected_explanations, data_quality
        ),
        "methodology": _methodology(analysis, data_quality),
        "top_sites": sites_section,
        "shortlist": shortlist,
        "cost_analysis": [
            {
                "site_id": str(item.get("site_id")),
                "acquisition_total": (item.get("totals") or {}).get("acquisition_total"),
                "setup_total": (item.get("totals") or {}).get("setup_total"),
                "recurring_monthly_total": (item.get("totals") or {}).get(
                    "recurring_monthly_total"
                ),
                "recurring_annual_total": (item.get("totals") or {}).get(
                    "recurring_annual_total"
                ),
                "initial_investment_total": (item.get("totals") or {}).get(
                    "initial_investment_total"
                ),
                "is_complete": (item.get("totals") or {}).get("is_complete"),
                "missing_components": item.get("missing_components") or [],
                "budget_results": item.get("budget_results") or [],
            }
            for item in cost_assessments
        ],
        "property_intelligence": {
            "sites": [
                {
                    "site_id": str(entry.get("site_id")),
                    "site_name": entry.get("site_name"),
                    "status": entry.get("status"),
                    "message": entry.get("message"),
                    "sources": entry.get("sources") or [],
                    "opportunity_count": len(entry.get("opportunities") or []),
                    "opportunities": entry.get("opportunities") or [],
                }
                for entry in property_results
            ],
            "note": (
                "External opportunities are third-party listings retrieved at the "
                "time shown. Availability, price and terms are not verified by "
                "this platform."
            ),
        },
        "comparison": comparison or {},
        "sensitivity": sensitivity or {},
        "data_quality": {
            "summary": data_quality.get("summary") or {},
            "sources": data_quality.get("sources") or [],
            "coverage": data_quality.get("coverage") or {},
            "backtesting": data_quality.get("backtesting") or {},
            "limitations": data_quality.get("limitations") or [],
        },
        "assumptions": _assumptions(analysis, data_quality),
        "source_information": _source_information(data_quality),
        "statement": (
            "This report is decision support produced by a deterministic "
            "multi-criteria analysis. It does not replace site visits, "
            "commercial due diligence or local market knowledge, and it does "
            "not claim certainty about trading performance."
        ),
    }

    return report


def _executive_summary(
    analysis: Mapping[str, Any],
    top_sites: Sequence[Mapping[str, Any]],
    explanations: Sequence[Mapping[str, Any]],
    data_quality: Mapping[str, Any],
) -> dict[str, Any]:
    """Compose the executive summary from computed values only."""

    name = analysis.get("name") or "Untitled analysis"
    business_type = analysis.get("business_type") or "the selected business type"

    if not top_sites:
        return {
            "headline": f"{name}: no ranked sites are available.",
            "paragraphs": [
                "No candidate sites could be scored for this analysis. The "
                "reason is reported in the data quality section."
            ],
            "recommendation": None,
        }

    best = top_sites[0]
    best_name = best.get("name") or f"Site {best.get('site_id')}"
    best_score = best.get("score")

    paragraphs = [
        f"This report evaluates candidate retail locations for {business_type} "
        f"across {len(top_sites)} shortlisted site"
        f"{'s' if len(top_sites) != 1 else ''}."
    ]

    if best_score is not None:
        paragraphs.append(
            f"{best_name} is the highest ranked site with a multi-criteria "
            f"score of {float(best_score):.3f}."
        )

    best_explanation = next(
        (
            item
            for item in explanations
            if str(item.get("site_id")) == str(best.get("site_id"))
        ),
        None,
    )
    if best_explanation and best_explanation.get("summary"):
        paragraphs.append(str(best_explanation["summary"]))

    summary = (data_quality.get("summary") or {})
    coverage = summary.get("criteria_coverage")
    if isinstance(coverage, (int, float)):
        paragraphs.append(
            f"The analysis scored {coverage * 100:.0f}% of the configured "
            "criterion weight with the current data release."
        )

    limitation_count = len(data_quality.get("limitations") or [])
    if limitation_count:
        paragraphs.append(
            f"{limitation_count} documented limitations of the underlying data "
            "are set out in the data quality section and must be read "
            "alongside this recommendation."
        )

    return {
        "headline": f"{name}: {best_name} is the leading candidate.",
        "paragraphs": paragraphs,
        "recommendation": {
            "site_id": best.get("site_id"),
            "site_name": best_name,
            "score": best_score,
            "next_steps": [
                "Complete a site visit during the intended trading hours.",
                "Obtain a commercial rent or sale valuation and confirm the terms.",
                "Verify title, approvals and the practicalities of servicing the site.",
                "Re-run this analysis with the quoted figures before committing capital.",
            ],
        },
    }


def _methodology(
    analysis: Mapping[str, Any], data_quality: Mapping[str, Any]
) -> dict[str, Any]:
    """Describe the analytical method that produced the ranking."""

    method = analysis.get("aggregation_method") or "weighted_sum"
    method_labels = {
        "weighted_sum": (
            "Weighted sum (SAW). Each criterion contributes in proportion to its "
            "weight; a strong criterion can offset a weak one."
        ),
        "weighted_product": (
            "Weighted product (WPM). A weak criterion is penalised more "
            "sharply because a near-zero factor drags down the whole product."
        ),
        "distance_to_ideal": (
            "Distance to ideal (TOPSIS-style). Each site is scored on its "
            "weighted distance to the best and worst observed value for every "
            "criterion."
        ),
    }

    coverage = (data_quality.get("summary") or {}).get("criteria_coverage")

    return {
        "steps": [
            "Candidate sites are filtered against any hard requirements the user set.",
            "Each scored criterion is normalised to a 0-1 scale using the observed "
            "range across the candidate set, after clipping to the 5th and 95th "
            "percentiles to limit the influence of outliers.",
            "Cost-oriented criteria are inverted so that lower raw values score higher; "
            "target-band criteria score highest inside an ideal range.",
            "Criterion weights are rolled down the criteria hierarchy and applied to "
            "the normalised values.",
            "Sites are ranked by the aggregated score, and requirement shortfalls are "
            "applied as a disclosed, bounded penalty.",
            "The ranking is stress-tested against weight perturbations, alternative "
            "aggregation methods and near-ties.",
        ],
        "aggregation_method": method,
        "aggregation_method_description": method_labels.get(
            method, "The configured aggregation method."
        ),
        "normalisation": "Min-max over the observed candidate range, after 5th/95th percentile clipping.",
        "weighting": (
            "Weights are set over the eight criteria categories and rolled down to the "
            "28 leaf criteria as the product of the level weights along each leaf's path."
        ),
        "hard_constraints": (
            "A requirement marked as a hard requirement excludes a site that fails it. "
            "A requirement marked as a preference keeps the site and reduces its score "
            "by at most the disclosed penalty rate. A flexible requirement is reported "
            "as a warning only."
        ),
        "criteria_coverage": coverage,
        "no_prediction_statement": (
            "The platform ranks candidate sites against a stated set of weights and "
            "requirements. It does not predict trading performance."
        ),
    }


def _assumptions(
    analysis: Mapping[str, Any], data_quality: Mapping[str, Any]
) -> list[str]:
    """List the assumptions that the analysis rests on."""

    assumptions: list[str] = [
        "The candidate site inventory is complete for the search area; sites that "
        "were never ingested cannot be considered.",
        "Normalisation is relative to the candidate set in this analysis, so scores "
        "change if the candidate set changes.",
        "The weights reflect the stated business strategy; a different weighting "
        "produces a different ranking.",
        "Facility and parking data is as accurate as the underlying map and listing "
        "data, which is uneven in coverage.",
    ]

    if (analysis.get("acquisition_mode") or "either") == "either":
        assumptions.append(
            "Because both purchase and lease economics were considered, the cost "
            "comparison between the two is only as reliable as the underlying "
            "published figures."
        )

    if not (data_quality.get("backtesting") or {}).get("available"):
        assumptions.append(
            "The model has not been validated against trading performance for this "
            "client, because no own-estate records are available."
        )

    return assumptions


def _source_information(data_quality: Mapping[str, Any]) -> list[dict[str, Any]]:
    """List the data sources that contributed to the analysis."""

    sources: list[dict[str, Any]] = []
    for source in data_quality.get("sources") or []:
        sources.append(
            {
                "label": source.get("label"),
                "origin": source.get("origin"),
                "table": source.get("table"),
                "available": source.get("available"),
            }
        )
    sources.append(
        {
            "label": "Scoring matrix",
            "origin": "Precomputed normalised decision matrix",
            "table": "normalized_matrix_versions",
            "available": bool(
                (data_quality.get("coverage") or {}).get("scoring_matrix", {}).get(
                    "available"
                )
            ),
        }
    )
    return sources


