'use client'

import * as React from 'react'
import { Download, FileText } from 'lucide-react'

import { Button } from '@/components/ui/button'
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from '@/components/ui/card'
import { ErrorState, LoadingState } from '@/components/ui/feedback'
import { exportRanking, generateReport } from '@/lib/api'
import { formatDateTime, formatMoney, formatScore } from '@/lib/format'

import { ExportPanel } from './export-panel'
import { useWorkspace } from './workspace-context'

type ReportPayload = {
  report_version: string
  generated_at: string
  analysis: Record<string, any>
  executive_summary: {
    headline: string
    paragraphs: string[]
    recommendation: { site_name: string; next_steps: string[] } | null
  }
  top_sites: {
    position: number
    site_id: string
    site_name: string
    score: number
    why: string | null
    caveats: string[]
    cost: { totals: Record<string, number | null> } | null
  }[]
  cost_analysis: Record<string, any>[]
  data_quality: { limitations: { title: string; detail: string }[] }
  assumptions: string[]
  statement: string
}

/**
 * Executive decision report.
 *
 * The report is generated by the backend from the deterministic results the
 * workspace already holds, and can be downloaded as JSON or printed.
 */
export function ReportPanel() {
  const { brief, scores, evaluation, siteById, criteria, weights, method } = useWorkspace()

  const [report, setReport] = React.useState<ReportPayload | null>(null)
  const [loading, setLoading] = React.useState(false)
  const [error, setError] = React.useState<string | null>(null)
  const [exportState, setExportState] = React.useState<'idle' | 'working' | 'done' | 'error'>(
    'idle',
  )
  const [exportMessage, setExportMessage] = React.useState<string | null>(null)

  /**
   * Export the reproducible ranking artefact.
   *
   * The export carries the exact weights and method that produced the
   * ranking, so the recommendation can be reproduced later.
   */
  const runExport = React.useCallback(async () => {
    if (!weights.category_weights) return
    setExportState('working')
    setExportMessage(null)
    try {
      const response = await exportRanking({
        weight_set: weights.category_weights,
        aggregation_method: method,
      })
      setExportState('done')
      setExportMessage(
        response.export_id
          ? `Export ${response.export_id} created. It contains the weights, method and ranked shortlist.`
          : 'The export was created and contains the weights, method and ranked shortlist.',
      )
    } catch (err) {
      setExportState('error')
      setExportMessage(
        err instanceof Error
          ? err.message
          : 'The export could not be created. The export service may require an authenticated session.',
      )
    }
  }, [weights.category_weights, method])

  const generate = React.useCallback(async () => {
    setLoading(true)
    setError(null)
    try {
      const response = await generateReport({
        analysis: {
          name: brief.name,
          business_type: brief.businessType,
          acquisition_mode: brief.acquisitionMode,
          location: brief.location,
          requirements: brief,
          weights: brief.weights,
          aggregation_method: brief.aggregationMethod,
          criteria_coverage: scores?.coverage ?? null,
        },
        ranking: (scores?.sites ?? []).map((row) => ({
          site_id: row.site_id,
          name: siteById[row.site_id]?.name ?? `Site ${row.site_id}`,
          score: row.score,
          rank: row.rank,
          latitude: siteById[row.site_id]?.coordinates.latitude ?? null,
          longitude: siteById[row.site_id]?.coordinates.longitude ?? null,
        })),
        explanations: [],
        cost_assessments: (evaluation?.sites ?? [])
          .map((item) => item.evaluation.cost)
          .filter((cost): cost is NonNullable<typeof cost> => cost !== null),
        property_results: [],
        sensitivity: {},
        data_quality: { limitations: [] },
        comparison: {},
      })
      setReport(response as unknown as ReportPayload)
    } catch (err) {
      setError(
        err instanceof Error ? err.message : 'The report could not be generated.',
      )
    } finally {
      setLoading(false)
    }
  }, [brief, scores, evaluation, siteById])

  return (
    <div className="space-y-5">
      <Card>
        <CardHeader>
          <div className="flex flex-wrap items-start justify-between gap-3">
            <div>
              <CardTitle>Executive decision report</CardTitle>
              <CardDescription>
                A presentable summary for regional management, strategy and property
                teams.
              </CardDescription>
            </div>
            <div className="flex flex-wrap gap-2">
              <Button type="button" onClick={generate} disabled={loading || !scores}>
                {loading ? <FileText className="animate-pulse" /> : <FileText />}
                {loading ? 'Generating…' : report ? 'Regenerate' : 'Generate report'}
              </Button>
            </div>
          </div>
        </CardHeader>

        <CardContent className="space-y-4">
          {error ? (
            <ErrorState
              title="The report could not be generated"
              description={error}
              onRetry={generate}
            />
          ) : null}

          {loading && !report ? <LoadingState label="Generating the report…" /> : null}

          {!report && !loading && !error ? (
            <p className="text-ink-muted text-sm leading-relaxed">
              The report is assembled from the ranking, the requirement evaluation, the
              cost position and the data quality findings. Generate it once the analysis
              has been run.
            </p>
          ) : null}

          {report ? (
            <article className="space-y-5">
              <header>
                <h3 className="text-ink text-lg font-semibold tracking-tight">
                  {report.analysis.name || 'Site selection report'}
                </h3>
                <p className="text-ink-subtle mt-0.5 text-[11px]">
                  Generated {formatDateTime(report.generated_at)} ·{' '}
                  {(report.analysis.business_type as string) || 'Business type not set'} ·{' '}
                  {(report.analysis.acquisition_mode as string) || 'either'}
                </p>
              </header>

              <section>
                <h4 className="section-eyebrow mb-1.5">Executive summary</h4>
                <p className="text-ink text-sm font-medium">{report.executive_summary.headline}</p>
                {report.executive_summary.paragraphs.map((paragraph, index) => (
                  <p key={index} className="text-ink-muted mt-1.5 text-xs leading-relaxed">
                    {paragraph}
                  </p>
                ))}
              </section>

              {report.top_sites.length > 0 ? (
                <section>
                  <h4 className="section-eyebrow mb-1.5">Shortlist</h4>
                  <ol className="space-y-2">
                    {report.top_sites.map((site) => (
                      <li key={site.site_id} className="border-line rounded-md border p-3">
                        <div className="flex flex-wrap items-baseline justify-between gap-2">
                          <p className="text-ink text-[13px] font-medium">
                            {site.position}. {site.site_name}
                          </p>
                          <p className="text-ink text-xs font-semibold tabular-nums">
                            {formatScore(site.score)}
                          </p>
                        </div>
                        {site.why ? (
                          <p className="text-ink-muted mt-1 text-xs leading-relaxed">{site.why}</p>
                        ) : null}
                        {site.cost ? (
                          <p className="text-ink-subtle mt-1 text-[11px]">
                            Initial investment:{' '}
                            {formatMoney(site.cost.totals.initial_investment_total)} · monthly:{' '}
                            {formatMoney(site.cost.totals.recurring_monthly_total)}
                          </p>
                        ) : null}
                        {site.caveats.length > 0 ? (
                          <ul className="text-ink-subtle mt-1.5 space-y-0.5 text-[11px]">
                            {site.caveats.map((caveat) => (
                              <li key={caveat}>{caveat}</li>
                            ))}
                          </ul>
                        ) : null}
                      </li>
                    ))}
                  </ol>
                </section>
              ) : null}

              {report.assumptions.length > 0 ? (
                <section>
                  <h4 className="section-eyebrow mb-1.5">Assumptions</h4>
                  <ul className="text-ink-muted list-disc space-y-1 pl-4 text-xs leading-relaxed">
                    {report.assumptions.map((assumption) => (
                      <li key={assumption}>{assumption}</li>
                    ))}
                  </ul>
                </section>
              ) : null}

              <div className="border-info-border bg-info-subtle rounded-md border px-3 py-2.5">
                <p className="text-info text-xs leading-relaxed">{report.statement}</p>
              </div>
            </article>
          ) : null}

          <ExportPanel report={report} />

          <div className="border-line rounded-md border p-4">
            <div className="flex flex-wrap items-start justify-between gap-3">
              <div className="min-w-0">
                <p className="text-ink text-[13px] font-medium">Reproducible export</p>
                <p className="text-ink-muted mt-0.5 text-[11px] leading-relaxed">
                  Creates a self-describing artefact containing the exact weights, the
                  aggregation method and the ranked shortlist, so the recommendation can
                  be reproduced later.
                </p>
              </div>
              <Button
                type="button"
                variant="outline"
                size="sm"
                onClick={runExport}
                disabled={exportState === 'working' || !weights.category_weights}
              >
                <Download />
                {exportState === 'working' ? 'Exporting…' : 'Create export'}
              </Button>
            </div>
            {exportMessage ? (
              <p
                className={
                  exportState === 'error'
                    ? 'text-danger mt-2.5 text-[11px] leading-relaxed'
                    : 'text-success mt-2.5 text-[11px] leading-relaxed'
                }
                role="status"
              >
                {exportMessage}
              </p>
            ) : null}
          </div>
        </CardContent>
      </Card>
    </div>
  )
}
