"""Site explainability API.

Produces the "why this site?" narrative for a candidate site from the
deterministic scoring engine, the requirement evaluation and the
sensitivity analysis.  Nothing in this router is generated by a language
model.
"""

from __future__ import annotations

from typing import Any, Optional

from fastapi import APIRouter, HTTPException, Request, status
from pydantic import BaseModel, Field

from app.domain.explanations import build_explanation
from scoring.requirement_fit import apply_fit_penalty, evaluate_site_requirements
from scoring.score import apply_weights, rank_sites
from scoring.weight_model import (
    WeightModelError,
    align_weights_to_columns,
    resolve_leaf_weights,
)

router = APIRouter(prefix="/explanations", tags=["Explainability"])


class ExplainRequest(BaseModel):
    """Request for a site explanation."""

    site_id: str = Field(..., min_length=1, description="The site to explain.")
    weights: Optional[dict[str, float]] = Field(
        default=None,
        description="Explicit leaf weights. Mutually exclusive with level_weights.",
    )
    level_weights: Optional[dict[str, Any]] = Field(
        default=None,
        description=(
            "Category weights and optional within-category leaf weights, e.g. "
            '{"category_weights": {"population": 0.3}, "leaf_weights": {}}.'
        ),
    )
    method: str = Field(default="weighted_sum")
    requirements: dict[str, Any] = Field(
        default_factory=dict,
        description="The confirmed requirement block, used for the requirement position.",
    )
    penalty_rate: float = Field(default=0.25, ge=0.0, le=1.0)
    compare_with: Optional[list[str]] = Field(
        default=None,
        description="Reference site identifiers to compare against.",
    )
    include_stability: bool = Field(
        default=True,
        description="Whether to include the rank-stability assessment.",
    )


@router.post("/site", summary="Explain why a site received its ranking")
def explain_site(payload: ExplainRequest, request: Request) -> dict[str, Any]:
    """Return a full, deterministic explanation for one site."""

    if (payload.weights is None) == (payload.level_weights is None):
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Provide exactly one of 'weights' or 'level_weights'.",
        )

    try:
        from app.routers.scenarios import get_normalized_matrix

        matrix = get_normalized_matrix()
    except Exception as exc:
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail=f"The normalised scoring matrix is unavailable: {exc}",
        ) from exc

    # --- Resolve the weights ------------------------------------------
    if payload.weights is not None:
        requested = dict(payload.weights)
    else:
        level = payload.level_weights or {}
        try:
            requested = resolve_leaf_weights(
                level.get("category_weights"),
                level.get("leaf_weights"),
            )
        except WeightModelError as exc:
            raise HTTPException(
                status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
                detail=str(exc),
            ) from exc

    aligned, dropped, coverage = align_weights_to_columns(
        requested, list(matrix.columns)
    )
    if not aligned:
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail=(
                "None of the requested criteria could be scored with the current "
                "data release."
            ),
        )

    method = payload.method.strip().lower().replace("-", "_").replace(" ", "_")
    scores = apply_weights(matrix, aligned, method=method)
    ranked = rank_sites(scores)

    site_row = None
    for index in matrix.index:
        if str(index) == str(payload.site_id):
            site_row = index
            break
    if site_row is None:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Site with id '{payload.site_id}' not found in the scoring matrix.",
        )

    # `rank_sites` returns a frame whose index has been reset, so the site
    # identifiers live in the `site_id` column rather than in the index.
    ordered_site_ids = list(ranked["site_id"])

    rank = int(ordered_site_ids.index(site_row)) + 1
    total_sites = int(len(ranked))
    base_score = float(scores.loc[site_row])

    focal_values = {
        str(column): float(matrix.loc[site_row, column]) for column in aligned
    }

    # --- Reference site ------------------------------------------------
    reference_values: Optional[dict[str, float]] = None
    reference_label: Optional[str] = None
    reference_candidates = payload.compare_with or []
    if not reference_candidates:
        # Default to the site immediately below, which is the most useful
        # comparison for a decision maker.
        position = ordered_site_ids.index(site_row)
        if position + 1 < len(ordered_site_ids):
            reference_candidates = [str(ordered_site_ids[position + 1])]

    for candidate in reference_candidates:
        match = None
        for index in matrix.index:
            if str(index) == str(candidate):
                match = index
                break
        if match is None:
            continue
        reference_values = {
            str(column): float(matrix.loc[match, column]) for column in aligned
        }
        reference_label = (
            f"the site ranked #{int(ordered_site_ids.index(match)) + 1}"
        )
        break

    # --- Requirement evaluation ----------------------------------------
    evaluation = None
    fit_factor = 1.0
    adjusted_score = base_score
    if payload.requirements:
        attributes = _site_attributes(request, payload.site_id)
        if attributes is not None:
            evaluation = evaluate_site_requirements(
                site_id=payload.site_id,
                attributes=attributes,
                requirements=payload.requirements,
                penalty_rate=payload.penalty_rate,
            )
            fit_factor = evaluation.fit_factor
            adjusted_score = apply_fit_penalty(base_score, fit_factor)

    # --- Stability ------------------------------------------------------
    stability: Optional[dict[str, Any]] = None
    if payload.include_stability:
        stability = _stability_for(request, payload.site_id, aligned, method)

    explanation = build_explanation(
        site_id=payload.site_id,
        site_name=_site_name(request, payload.site_id),
        rank=rank,
        total_sites=total_sites,
        base_score=base_score,
        adjusted_score=adjusted_score,
        fit_factor=fit_factor,
        focal_criteria=focal_values,
        focal_weights=aligned,
        reference_criteria=reference_values,
        reference_label=reference_label,
        evaluation=evaluation,
        stability=stability,
        coverage=coverage,
        dropped_criteria=dropped,
    )

    explanation["eligible"] = evaluation.eligible if evaluation else True
    explanation["hard_failures"] = (
        [check.to_dict() for check in evaluation.hard_failures] if evaluation else []
    )
    return explanation


def _site_name(request: Request, site_id: str) -> Optional[str]:
    try:
        from app.routers.sites import get_sites_dataframe

        sites_df = get_sites_dataframe(request)
    except Exception:
        return None
    for _, row in sites_df.iterrows():
        candidate = str(row.get("site_id") or row.get("id") or row.name)
        if candidate == str(site_id):
            name = row.get("name")
            return str(name) if name else None
    return None


def _site_attributes(request: Request, site_id: str) -> Optional[dict[str, Any]]:
    """Return the attribute mapping for a site, or ``None`` when unavailable."""

    try:
        from app.routers.sites import get_sites_dataframe

        sites_df = get_sites_dataframe(request)
    except Exception:
        return None

    for _, row in sites_df.iterrows():
        candidate = str(row.get("site_id") or row.get("id") or row.name)
        if candidate != str(site_id):
            continue
        attributes: dict[str, Any] = {}
        for key, value in row.items():
            if value is None:
                continue
            attributes[str(key)] = value
        return attributes
    return None


def _stability_for(
    request: Request,
    site_id: str,
    weights: dict[str, float],
    method: str,
) -> Optional[dict[str, Any]]:
    """Return the rank-stability row for a site, if it can be computed."""

    try:
        from app.core.matrix_store import load_normalized_matrix
        from sensitivity.stability import rank_stability_report

        matrix = load_normalized_matrix()
        report = rank_stability_report(matrix, weights, method=method)
    except Exception:
        return None

    for _, row in report.iterrows():
        if str(row["site_id"]) == str(site_id):
            return {
                "stability_percentage": float(row.get("stability_percentage", 0.0)),
                "stability_criterion": str(row.get("stability_criterion", "")),
                "current_rank": int(row.get("current_rank", 0)),
            }
    return None

